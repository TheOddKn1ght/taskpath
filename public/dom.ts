type Selected<S extends string> = S extends `${string} input` ? HTMLInputElement : S extends keyof Elements ? Elements[S] : S extends keyof HTMLElementTagNameMap ? HTMLElementTagNameMap[S] : HTMLElement;
export function select<S extends string>(selector:S, root:ParentNode=document): Selected<S> {
  const node=root.querySelector(selector);

  return node as Selected<S>;
}
export function selectAll<S extends string>(selector:S, root:ParentNode=document): Selected<S>[] { return [...root.querySelectorAll(selector)] as Selected<S>[]; }
